"""Turn a timing table into msfcore firmware that sends frames, and refuse it unless
the deadline checker proves that every edge is on time.

A table (what tools/msf_learn.py writes, or by hand) says, in clock cycles:
  pin, idle       the uio pin, and the level it rests at
  symbols         name -> phases [level, cycles]: zero, one, and if used leader,
                  trailer, gap
  carrier         {period, high}: phases at level != idle are bursts of this carrier
  serial          {bit, data_bits, parity, stops}: frames are UART characters
  frames          [{bits, word}]: what to send, the first bit in the word's bit 0

    python tools/msf_gen.py remote.json -o remote.s        fails if not certified

Every phase is a deadline on the cycle counter, so a program's timing doesn't depend
on which bits it sends. uo_out = DONE when all the frames are out.
"""
import argparse
import json
import os
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import msf_timing  # noqa: E402

MAX_WAIT = 60000         # WAIT_CMP reaches 65,280 ahead; longer phases are split


class Refused(Exception):
    pass


def advance(lines, cycles):
    """Move the deadline on by `cycles`, waiting on the way if it is further than a
    WAIT_CMP reaches."""
    while cycles > MAX_WAIT:
        lines += [f"        LDI      R6, {MAX_WAIT}", "        ADDS     R5, R5, R6",
                  "        WAIT_CMP R5"]
        cycles -= MAX_WAIT
    if cycles < 256:
        lines.append(f"        LDR      R6, #{cycles}")
    else:
        lines.append(f"        LDI      R6, {cycles}")
    lines.append("        ADDS     R5, R5, R6")


def phase(lines, level, cycles, table, label):
    """One phase: wait for its start, change the pin at once, then work out when it
    ends. So the time between an edge and the code that comes before the next wait
    (a return, a bit test) is inside the phase, and no path moves an edge."""
    mask = f"(1 << {table['pin']})"
    carrier = table.get("carrier")
    if carrier and level != table["idle"]:
        period, high = carrier["period"], carrier["high"]
        n = max(1, round(cycles / period))
        lines += [f"        LDI      R0, {n}", f"{label}_c:", "        WAIT_CMP R5"]
        lines.append(f"        PIN_{'SET' if not table['idle'] else 'CLR'}  {mask}")
        advance(lines, high)
        lines.append("        WAIT_CMP R5")
        lines.append(f"        PIN_{'CLR' if not table['idle'] else 'SET'}  {mask}")
        advance(lines, period - high)
        lines += ["        DECR     R0", f"        JNZ      {label}_c"]
        return
    lines += ["        WAIT_CMP R5", f"        PIN_{'SET' if level else 'CLR'}  {mask}"]
    advance(lines, cycles)


def generate(table):
    """The table -> assembly text."""
    pin, idle = table["pin"], table["idle"]
    mask = f"(1 << {pin})"
    head = [f"; Generated by tools/msf_gen.py from a timing table ({table.get('model', 'by hand')}).",
            f"; Sends {len(table['frames'])} frames on uio[{pin}], every phase on the cycle counter.",
            '.include "msf.inc"', "",
            "start:  LDR      R1, #0", "        TMO      R1",
            f"        PIN_{'SET' if idle else 'CLR'}  {mask}", f"        OE_SET   {mask}",
            "        CNT_R    R5"]
    advance(head, 400)
    body = []
    subs = []
    symbols = table["symbols"]
    for name, phases in symbols.items():
        subs.append(f"sym_{name}:")
        for i, (level, cycles) in enumerate(phases):
            phase(subs, level, cycles, table, f"sym_{name}_{i}")
        subs.append("        RET")
    if "serial" in table:
        s = table["serial"]
        subs += ["; R1 = a character, LSB first; uses R2, R3", "char:   MOV      R3, R7"]
        subs.append("        LDR      R4, #0")      # parity
        subs.append("        CALL     sym_zero")    # the start bit
        subs.append(f"        LDR      R2, #{s['data_bits']}")
        subs += ["ch1:    LDR      R0, #1", "        AND      R0, R1, R0",
                 "        XOR      R4, R4, R0", "        ADDS     R0, R0, R0",
                 "        JZ       ch0", "        CALL     sym_one", "        JMP      ch2",
                 "ch0:    CALL     sym_zero", "ch2:    SHR      R1, R1, #1",
                 "        DECR     R2", "        JNZ      ch1"]
        if s["parity"]:
            even = s["parity"] == "even"
            subs += ["        ADDS     R4, R4, R4", f"        {'JZ' if even else 'JNZ'}       chp0",
                     "        CALL     sym_one", "        JMP      chp1", "chp0:   CALL     sym_zero", "chp1:"]
        for _ in range(s["stops"]):
            subs.append("        CALL     sym_one")
        subs += ["        MOV      R7, R3", "        RET"]
    # the frames: their words live in the program, read with LD
    data, labels = [], []
    for i, fr in enumerate(table["frames"]):
        bits, word = fr["bits"], fr["word"]
        chunks = [(word >> (16 * k)) & 0xFFFF for k in range((bits + 15) // 16)]
        lab = f"msg{i}"
        data.append(f"{lab}:   .word " + ", ".join(f"0x{c:04X}" for c in chunks))
        labels.append((lab, bits))
    for i, (lab, bits) in enumerate(labels):
        body.append(f"; frame {i}")
        if "serial" in table:
            body += [f"        LDI      R2, {lab}", "        LD       R1, R2", "        CALL     char"]
            continue
        if "leader" in symbols:
            body.append("        CALL     sym_leader")
        # inline, so that a return address never goes through memory, where the
        # checker could not follow it
        body += [f"        LDI      R3, {lab}", f"        LDR      R2, #{bits}",
                 f"f{i}_w:  LD       R1, R3", "        INCR     R3", "        LDR      R4, #16",
                 f"f{i}_b:  LDR      R0, #1", "        AND      R0, R1, R0",
                 "        ADDS     R0, R0, R0", f"        JZ       f{i}_0",
                 "        CALL     sym_one", f"        JMP      f{i}_x",
                 f"f{i}_0:  CALL     sym_zero", f"f{i}_x:  SHR      R1, R1, #1",
                 "        DECR     R2", f"        JZ       f{i}_e", "        DECR     R4",
                 f"        JNZ      f{i}_b", f"        JMP      f{i}_w", f"f{i}_e:"]
        if "trailer" in symbols:
            body.append("        CALL     sym_trailer")
        if symbols.get("gap", [[0, 0]])[0][1] > 0 and i + 1 < len(labels):
            body.append("        CALL     sym_gap")
    tail = ["        WAIT_CMP R5", f"        PIN_{'SET' if idle else 'CLR'}  {mask}",
            "        UO_WI    DONE",
            "halt:   JMP      halt", ""]
    return "\n".join(head + body + tail + subs + data) + "\n"


def certify(text):
    """Refused unless msf_timing.py proves every deadline."""
    with tempfile.TemporaryDirectory() as tmp:
        path = os.path.join(tmp, "gen.s")
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)
        an, words, _ = msf_timing.analyse(path)
    if not msf_timing.certified(an):
        bad = [f"{pc:#05x} {an.src.get(pc, '')}: d {dl['lo']}" for pc, dl in an.deadlines.items()
               if dl["late"] or dl["unchecked"]]
        raise Refused("the checker cannot prove every deadline: " + "; ".join(bad[:4]))
    if len(words) > 896:
        raise Refused(f"{len(words)} words does not fit 896")
    worst = min(dl["lo"] for dl in an.deadlines.values()) - 1
    return an, words, worst


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("table")
    ap.add_argument("-o", required=True)
    a = ap.parse_args()
    with open(a.table, encoding="utf-8") as f:
        table = json.load(f)
    text = generate(table)
    try:
        _, words, worst = certify(text)
    except Refused as e:
        print(f"refused: {e}", file=sys.stderr)
        return 1
    with open(a.o, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"{a.o}: {len(words)} words, every deadline certified, worst slack {worst} cycles")
    return 0


if __name__ == "__main__":
    sys.exit(main())
